begin
  if v_player is null then raise exception 'UNAUTHORIZED'; end if;
  if not exists(select 1 from public.players where id=v_player and account_status='active')
    then raise exception 'PLAYER_NOT_AVAILABLE'; end if;

  v_tournament:=private.ensure_active_tournament();

  perform 1 from public.tournaments
  where id=v_tournament and status='registration' and registration_ends_at>now()
  for update;
  if not found then raise exception 'REGISTRATION_CLOSED'; end if;

  insert into public.tournament_entries(tournament_id,player_id)
  values(v_tournament,v_player)
  on conflict(tournament_id,player_id) do nothing;

  select count(*) into v_count from public.tournament_entries where tournament_id=v_tournament;
  if v_count>8 then
    delete from public.tournament_entries where tournament_id=v_tournament and player_id=v_player;
    raise exception 'TOURNAMENT_FULL';
  end if;

  if v_count=8 then
    perform private.start_tournament(v_tournament);
  end if;

  return jsonb_build_object('tournamentId',v_tournament,'joined',true,'entries',v_count,'maxPlayers',8);
end;
$function$;


