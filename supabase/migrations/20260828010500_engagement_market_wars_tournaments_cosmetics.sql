CREATE OR REPLACE FUNCTION private.refresh_player_cosmetics(p_player uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  p public.players%rowtype;
  d public.cosmetic_definitions%rowtype;
  v_ok boolean;
  v_count integer;
  v_guild_level integer;
  v_min integer;
  v_max integer;
  v_target integer;
begin
  select * into p from public.players where id=p_player;
  if p.id is null then return; end if;

  select g.level into v_guild_level
  from public.guild_members gm join public.guilds g on g.id=gm.guild_id
  where gm.player_id=p_player limit 1;
  v_guild_level:=coalesce(v_guild_level,0);

  for d in select * from public.cosmetic_definitions where active order by sort_order loop
    v_ok:=false;

    if d.unlock_type='default' then
      v_ok:=true;
    elsif d.unlock_type='level' then
      v_ok:=p.level>=d.threshold;
    elsif d.unlock_type='rating' then
      v_ok:=p.battle_rating>=d.threshold;
    elsif d.unlock_type='wins' then
      v_ok:=p.battle_wins>=d.threshold;
    elsif d.unlock_type='guild_level' then
      v_ok:=v_guild_level>=d.threshold;
    elsif d.unlock_type='unique_cards' then
      select count(*) into v_count from public.player_cards where player_id=p_player and quantity>0;
      v_ok:=v_count>=d.threshold;
    elsif d.unlock_type='season_points' then
      select coalesce(max(points),0) into v_count from public.player_seasons where player_id=p_player;
      v_ok:=v_count>=d.threshold;
    elsif d.unlock_type='pokedex_gen' then
      if d.threshold=1 then v_min:=1;v_max:=151;
      elsif d.threshold=2 then v_min:=152;v_max:=251;
      elsif d.threshold=3 then v_min:=252;v_max:=386;
      elsif d.threshold=4 then v_min:=387;v_max:=493;
      elsif d.threshold=5 then v_min:=494;v_max:=649;
      elsif d.threshold=6 then v_min:=650;v_max:=721;
      elsif d.threshold=7 then v_min:=722;v_max:=809;
      elsif d.threshold=8 then v_min:=810;v_max:=905;
      else v_min:=906;v_max:=1025;
      end if;
      v_target:=v_max-v_min+1;
      select count(distinct n) into v_count
      from public.player_cards pc
      join public.cards c on c.id=pc.card_id
      cross join lateral unnest(coalesce(c.pokedex_numbers,array[]::integer[])) n
      where pc.player_id=p_player and pc.quantity>0 and n between v_min and v_max;
      v_ok:=v_count>=v_target;
    end if;

    if v_ok then
      insert into public.player_cosmetics(player_id,cosmetic_id)
      values(p_player,d.id)
      on conflict do nothing;
    end if;
  end loop;

  if p.equipped_frame_id is null then
    update public.players set equipped_frame_id='frame_classic' where id=p_player;
  end if;
  if p.equipped_background_id is null then
    update public.players set equipped_background_id='bg_midnight' where id=p_player;
  end if;
end;
$function$;


CREATE OR REPLACE FUNCTION private.respond_market_offer(p_offer_id uuid, p_accept boolean)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_actor uuid:=auth.uid();
  v_offer public.market_offers%rowtype;
  v_listing public.market_listings%rowtype;
  v_buyer_coins bigint;
  v_buyer_after bigint;
  v_seller_after bigint;
  v_card_name text;
begin
  if v_actor is null then raise exception 'UNAUTHORIZED'; end if;

  select * into v_offer
  from public.market_offers
  where id=p_offer_id
  for update;
  if not found then raise exception 'OFFER_NOT_FOUND'; end if;

  select * into v_listing
  from public.market_listings
  where id=v_offer.listing_id
  for update;
  if not found then raise exception 'LISTING_NOT_FOUND'; end if;
  if v_listing.seller_id<>v_actor then raise exception 'FORBIDDEN'; end if;
  if v_offer.status<>'pending' then raise exception 'OFFER_NOT_PENDING'; end if;

  if v_offer.expires_at<=now() then
    update public.market_offers set status='expired',updated_at=now() where id=v_offer.id;
    raise exception 'OFFER_EXPIRED';
  end if;

  select pokemon_name into v_card_name from public.cards where id=v_listing.card_id;

  if not coalesce(p_accept,false) then
    update public.market_offers
    set status='rejected',updated_at=now()
    where id=v_offer.id;

    perform public.server_queue_notification(
      v_offer.buyer_id,'market_offer_rejected','Oferta recusada',
      'Sua oferta por '||coalesce(v_card_name,'uma carta')||' foi recusada.',
      jsonb_build_object('offerId',v_offer.id,'listingId',v_listing.id)
    );

    return jsonb_build_object('id',v_offer.id,'status','rejected');
  end if;

  if v_listing.status<>'active' then raise exception 'LISTING_NOT_ACTIVE'; end if;

  perform 1 from public.players
  where id in (v_offer.buyer_id,v_actor)
  order by id
  for update;

  select coins into v_buyer_coins
  from public.players
  where id=v_offer.buyer_id and account_status='active';
  if not found then raise exception 'BUYER_NOT_AVAILABLE'; end if;
  if v_buyer_coins<v_offer.amount_coins then raise exception 'BUYER_NOT_ENOUGH_COINS'; end if;

  update public.players
  set coins=coins-v_offer.amount_coins
  where id=v_offer.buyer_id
  returning coins into v_buyer_after;

  update public.players
  set coins=coins+v_offer.amount_coins
  where id=v_actor
  returning coins into v_seller_after;

  insert into public.player_cards(player_id,card_id,quantity)
  values(v_offer.buyer_id,v_listing.card_id,v_listing.quantity)
  on conflict(player_id,card_id)
  do update set quantity=public.player_cards.quantity+excluded.quantity;

  update public.market_listings
  set status='sold',buyer_id=v_offer.buyer_id,sold_at=now(),updated_at=now()
  where id=v_listing.id;

  update public.market_offers
  set status=case when id=v_offer.id then 'accepted' else 'rejected' end,
      updated_at=now()
  where listing_id=v_listing.id and status='pending';

  perform public.server_queue_notification(
    v_offer.buyer_id,'market_offer_accepted','Oferta aceita!',
    'Sua oferta por '||coalesce(v_card_name,'uma carta')||' foi aceita. A carta já está na sua Bag.',
    jsonb_build_object('offerId',v_offer.id,'listingId',v_listing.id,'cardId',v_listing.card_id,'amountCoins',v_offer.amount_coins)
  );

  return jsonb_build_object(
    'id',v_offer.id,'status','accepted','listingId',v_listing.id,
    'cardId',v_listing.card_id,'quantity',v_listing.quantity,
    'amountCoins',v_offer.amount_coins,'buyerCoins',v_buyer_after,'sellerCoins',v_seller_after
  );
end;
$function$;


CREATE OR REPLACE FUNCTION private.start_tournament(p_tournament uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_players uuid[];
  v_count integer;
  i integer;
begin
  select count(*) into v_count
  from public.tournament_entries
  where tournament_id=p_tournament;

  if v_count<>8 then return; end if;

  update public.tournaments
  set status='active',starts_at=coalesce(starts_at,now())
  where id=p_tournament and status='registration';

  if not found then return; end if;

  select array_agg(player_id order by random())
  into v_players
  from public.tournament_entries
  where tournament_id=p_tournament;

  for i in 1..8 loop
    update public.tournament_entries
    set seed=i
    where tournament_id=p_tournament and player_id=v_players[i];
  end loop;

  for i in 1..4 loop
    insert into public.tournament_matches(
      tournament_id,round_no,slot_no,player_a_id,player_b_id,status
    )
    values(
      p_tournament,1,i,v_players[(i-1)*2+1],v_players[(i-1)*2+2],'ready'
    )
    on conflict(tournament_id,round_no,slot_no) do nothing;

    perform private.create_tournament_match_battle(
      p_tournament,1,i,v_players[(i-1)*2+1],v_players[(i-1)*2+2]
    );
  end loop;
end;
$function$;


