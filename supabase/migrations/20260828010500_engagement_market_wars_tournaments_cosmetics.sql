CREATE OR REPLACE FUNCTION private.claim_guild_collective_booster()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_player uuid:=auth.uid();
  v_guild text;
  v_id uuid;
  v_booster public.guild_collective_boosters%rowtype;
  v_cards jsonb;
begin
  if v_player is null then raise exception 'UNAUTHORIZED'; end if;
  select guild_id into v_guild from public.guild_members where player_id=v_player limit 1;
  if v_guild is null then raise exception 'NO_GUILD'; end if;

  v_id:=private.ensure_guild_collective_booster(v_guild);
  select * into v_booster from public.guild_collective_boosters where id=v_id for update;
  if v_booster.status<>'ready' then raise exception 'GUILD_BOOSTER_NOT_READY'; end if;
  if exists(select 1 from public.guild_collective_booster_claims where booster_id=v_id and player_id=v_player)
    then raise exception 'ALREADY_CLAIMED'; end if;

  with guaranteed as (
    select c.id,c.pokemon_name,c.rarity,c.image_small,c.image_large,
      coalesce(pc.quantity,0)>0 already_owned
    from public.cards c
    left join public.player_cards pc on pc.player_id=v_player and pc.card_id=c.id
    where public.rarity_tier(c.rarity)>=4
    order by (-ln(greatest(random(),0.0000001))/greatest(0.000001,public.rarity_pull_weight(c.rarity)))
    limit 1
  ), filler as (
    select c.id,c.pokemon_name,c.rarity,c.image_small,c.image_large,
      coalesce(pc.quantity,0)>0 already_owned
    from public.cards c
    left join public.player_cards pc on pc.player_id=v_player and pc.card_id=c.id
    where c.id not in(select id from guaranteed)
    order by (-ln(greatest(random(),0.0000001))/greatest(0.000001,public.rarity_pull_weight(c.rarity)))
    limit 4
  ), picked as (
    select * from guaranteed
    union all
    select * from filler
  ), upserted as (
    insert into public.player_cards(player_id,card_id,quantity)
    select v_player,id,1 from picked
    on conflict(player_id,card_id) do update set quantity=public.player_cards.quantity+1
    returning card_id
  )
  select jsonb_agg(jsonb_build_object(
    'id',id,'name',pokemon_name,'rarity',rarity,
    'image',coalesce(nullif(image_large,''),nullif(image_small,'')),
    'imageLarge',nullif(image_large,''),'imageSmall',nullif(image_small,''),
    'isNew',not already_owned,'wishlistHit',false
  ))
  into v_cards
  from picked;

  insert into public.guild_collective_booster_claims(booster_id,player_id,cards_received)
  values(v_id,v_player,coalesce(v_cards,'[]'::jsonb));

  perform public.server_refresh_player_achievements(v_player);

  return jsonb_build_object(
    'boosterId',v_id,'guildId',v_guild,'cards',coalesce(v_cards,'[]'::jsonb),'claimed',true
  );
