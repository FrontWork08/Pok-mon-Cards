CREATE OR REPLACE FUNCTION private.add_collective_booster_progress(p_player_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_guild text;
  v_id uuid;
begin
  select guild_id into v_guild from public.guild_members where player_id=p_player_id limit 1;
  if v_guild is null then return; end if;
  v_id:=private.ensure_guild_collective_booster(v_guild);

  update public.guild_collective_boosters
  set progress=least(target,progress+1),
      status=case when progress+1>=target then 'ready' else status end,
      ready_at=case when progress+1>=target and ready_at is null then now() else ready_at end
  where id=v_id and status='building';
end;
$function$;


CREATE OR REPLACE FUNCTION private.apply_guild_war_battle_progress()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_winner_guild text;
  v_loser uuid;
  v_loser_guild text;
  v_war public.guild_wars%rowtype;
begin
  if new.status<>'completed' or old.status='completed' or not new.is_ranked or new.winner_id is null then
    return new;
  end if;

  perform private.ensure_weekly_guild_wars();

  v_loser:=case when new.winner_id=new.challenger_id then new.opponent_id else new.challenger_id end;

  select guild_id into v_winner_guild
  from public.guild_members where player_id=new.winner_id limit 1;
  select guild_id into v_loser_guild
  from public.guild_members where player_id=v_loser limit 1;

  if v_winner_guild is null or v_loser_guild is null or v_winner_guild=v_loser_guild then
    return new;
  end if;

  select * into v_war
  from public.guild_wars
  where status='active'
    and starts_at<=now() and ends_at>now()
    and (
      (guild_a_id=v_winner_guild and guild_b_id=v_loser_guild)
      or (guild_b_id=v_winner_guild and guild_a_id=v_loser_guild)
    )
  order by starts_at desc
  limit 1
  for update;

  if v_war.id is null then return new; end if;

  if v_winner_guild=v_war.guild_a_id then
    update public.guild_wars set score_a=score_a+3 where id=v_war.id;
  else
    update public.guild_wars set score_b=score_b+3 where id=v_war.id;
  end if;

  if v_loser_guild=v_war.guild_a_id then
    update public.guild_wars set score_a=score_a+1 where id=v_war.id;
  else
    update public.guild_wars set score_b=score_b+1 where id=v_war.id;
  end if;

  insert into public.guild_war_player_points(war_id,player_id,guild_id,points,wins,matches)
  values(v_war.id,new.winner_id,v_winner_guild,3,1,1)
  on conflict(war_id,player_id) do update
  set points=public.guild_war_player_points.points+3,
      wins=public.guild_war_player_points.wins+1,
      matches=public.guild_war_player_points.matches+1,
      updated_at=now();

  insert into public.guild_war_player_points(war_id,player_id,guild_id,points,wins,matches)
  values(v_war.id,v_loser,v_loser_guild,1,0,1)
  on conflict(war_id,player_id) do update
  set points=public.guild_war_player_points.points+1,
      matches=public.guild_war_player_points.matches+1,
      updated_at=now();

  return new;
end;
$function$;


CREATE OR REPLACE FUNCTION private.apply_pack_guild_xp()
