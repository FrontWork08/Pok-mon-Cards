CREATE OR REPLACE FUNCTION private.ensure_weekly_guild_wars()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_week date:=date_trunc('week',now())::date;
  v_cycle integer:=mod(extract(week from now())::integer,3);
  r record;
  v_winner text;
begin
  for r in
    select * from public.guild_wars
    where status='active' and ends_at<=now()
    for update
  loop
    v_winner:=case
      when r.score_a>r.score_b then r.guild_a_id
      when r.score_b>r.score_a then r.guild_b_id
      else null
    end;

    update public.guild_wars
    set status='completed',winner_guild_id=v_winner
    where id=r.id;

    if v_winner is not null then
      update public.guilds
      set xp=xp+100,
          level=greatest(level,1+floor((xp+100)/500.0)::integer)
      where id=v_winner;
    end if;
  end loop;

  if not (
    exists(select 1 from public.guilds where id='kanto') and
    exists(select 1 from public.guilds where id='johto') and
    exists(select 1 from public.guilds where id='hoenn') and
    exists(select 1 from public.guilds where id='sinnoh')
  ) then
    return;
  end if;

  if v_cycle=0 then
    insert into public.guild_wars(week_start,guild_a_id,guild_b_id,starts_at,ends_at)
    values
      (v_week,'kanto','johto',v_week::timestamptz,(v_week+7)::timestamptz),
      (v_week,'hoenn','sinnoh',v_week::timestamptz,(v_week+7)::timestamptz)
    on conflict(week_start,guild_a_id,guild_b_id) do nothing;
  elsif v_cycle=1 then
    insert into public.guild_wars(week_start,guild_a_id,guild_b_id,starts_at,ends_at)
    values
      (v_week,'kanto','hoenn',v_week::timestamptz,(v_week+7)::timestamptz),
      (v_week,'johto','sinnoh',v_week::timestamptz,(v_week+7)::timestamptz)
    on conflict(week_start,guild_a_id,guild_b_id) do nothing;
  else
    insert into public.guild_wars(week_start,guild_a_id,guild_b_id,starts_at,ends_at)
    values
      (v_week,'kanto','sinnoh',v_week::timestamptz,(v_week+7)::timestamptz),
      (v_week,'johto','hoenn',v_week::timestamptz,(v_week+7)::timestamptz)
    on conflict(week_start,guild_a_id,guild_b_id) do nothing;
  end if;
end;
$function$;


