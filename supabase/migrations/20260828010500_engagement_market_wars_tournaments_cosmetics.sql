CREATE OR REPLACE FUNCTION private.create_market_offer(p_listing_id uuid, p_amount bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_actor uuid:=auth.uid();
  v_listing public.market_listings%rowtype;
  v_coins bigint;
  v_offer uuid;
  v_card_name text;
begin
  if v_actor is null then raise exception 'UNAUTHORIZED'; end if;
  if p_listing_id is null or p_amount is null or p_amount<1 or p_amount>100000000
    then raise exception 'INVALID_OFFER'; end if;

  update public.market_offers
  set status='expired',updated_at=now()
  where status='pending' and expires_at<=now();

  select * into v_listing
  from public.market_listings
  where id=p_listing_id
  for update;
  if not found then raise exception 'LISTING_NOT_FOUND'; end if;
  if v_listing.status<>'active' then raise exception 'LISTING_NOT_ACTIVE'; end if;
  if v_listing.seller_id=v_actor then raise exception 'CANNOT_OFFER_OWN_LISTING'; end if;

  select coins into v_coins
  from public.players
  where id=v_actor and account_status='active'
  for update;
  if not found then raise exception 'PLAYER_NOT_AVAILABLE'; end if;
  if v_coins<p_amount then raise exception 'NOT_ENOUGH_COINS'; end if;

  update public.market_offers
  set status='cancelled',updated_at=now()
  where listing_id=p_listing_id and buyer_id=v_actor and status='pending';

  insert into public.market_offers(listing_id,buyer_id,amount_coins)
  values(p_listing_id,v_actor,p_amount)
  returning id into v_offer;

  select pokemon_name into v_card_name from public.cards where id=v_listing.card_id;

  perform public.server_queue_notification(
    v_listing.seller_id,
    'market_offer',
    'Nova oferta no mercado',
    'Recebeu uma oferta de 🪙 '||p_amount||' por '||coalesce(v_card_name,'uma carta')||'.',
    jsonb_build_object('offerId',v_offer,'listingId',p_listing_id,'buyerId',v_actor,'amountCoins',p_amount)
  );

  return jsonb_build_object(
    'id',v_offer,'listingId',p_listing_id,'amountCoins',p_amount,
    'status','pending','expiresAt',now()+interval '24 hours'
  );
end;
$function$;


