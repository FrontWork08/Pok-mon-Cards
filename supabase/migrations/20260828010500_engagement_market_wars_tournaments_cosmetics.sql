CREATE OR REPLACE FUNCTION private.apply_tournament_battle_result()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_match public.tournament_matches%rowtype;
  v_next_round integer;
  v_next_slot integer;
  v_next public.tournament_matches%rowtype;
  v_reward_coins bigint;
  v_reward_diamonds integer;
begin
  if new.status<>'completed' or old.status='completed' or new.winner_id is null then
    return new;
  end if;

  select * into v_match
  from public.tournament_matches
  where battle_id=new.id
  for update;
  if v_match.id is null then return new; end if;

  update public.tournament_matches
  set winner_id=new.winner_id,status='completed',updated_at=now()
  where id=v_match.id;

  if v_match.round_no=3 then
    update public.tournaments
    set status='completed',winner_id=new.winner_id
    where id=v_match.tournament_id and status='active'
    returning reward_coins,reward_diamonds into v_reward_coins,v_reward_diamonds;

    if found then
      update public.players
      set coins=coins+v_reward_coins,diamonds=diamonds+v_reward_diamonds
      where id=new.winner_id;

      perform public.server_queue_notification(
        new.winner_id,'tournament_champion','Você é campeão!',
        'Você venceu a Copa Trainer e recebeu 🪙 '||v_reward_coins||' + 💎 '||v_reward_diamonds||'.',
        jsonb_build_object('tournamentId',v_match.tournament_id,'coins',v_reward_coins,'diamonds',v_reward_diamonds)
      );
    end if;
    return new;
  end if;

  v_next_round:=v_match.round_no+1;
  v_next_slot:=ceil(v_match.slot_no/2.0)::integer;

  insert into public.tournament_matches(
    tournament_id,round_no,slot_no,
    player_a_id,player_b_id,status
  )
  values(
    v_match.tournament_id,v_next_round,v_next_slot,
    case when mod(v_match.slot_no,2)=1 then new.winner_id else null end,
    case when mod(v_match.slot_no,2)=0 then new.winner_id else null end,
    'pending'
  )
  on conflict(tournament_id,round_no,slot_no) do update
  set player_a_id=case
        when mod(v_match.slot_no,2)=1 then new.winner_id
        else public.tournament_matches.player_a_id
      end,
      player_b_id=case
        when mod(v_match.slot_no,2)=0 then new.winner_id
        else public.tournament_matches.player_b_id
      end,
      updated_at=now();

  select * into v_next
  from public.tournament_matches
  where tournament_id=v_match.tournament_id and round_no=v_next_round and slot_no=v_next_slot
  for update;

  if v_next.player_a_id is not null and v_next.player_b_id is not null and v_next.battle_id is null then
    update public.tournament_matches set status='ready' where id=v_next.id;
    perform private.create_tournament_match_battle(
      v_next.tournament_id,v_next.round_no,v_next.slot_no,v_next.player_a_id,v_next.player_b_id
    );
  end if;

  return new;
end;
$function$;


CREATE OR REPLACE FUNCTION private.cancel_market_offer(p_offer_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_actor uuid:=auth.uid();
  v_offer public.market_offers%rowtype;
begin
  if v_actor is null then raise exception 'UNAUTHORIZED'; end if;

  select * into v_offer from public.market_offers where id=p_offer_id for update;
  if not found then raise exception 'OFFER_NOT_FOUND'; end if;
  if v_offer.buyer_id<>v_actor then raise exception 'FORBIDDEN'; end if;
  if v_offer.status<>'pending' then raise exception 'OFFER_NOT_PENDING'; end if;

  update public.market_offers
  set status='cancelled',updated_at=now()
  where id=v_offer.id;

  return jsonb_build_object('id',v_offer.id,'status','cancelled');
end;
$function$;


