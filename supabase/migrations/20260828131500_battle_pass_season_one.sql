create or replace function private.trg_battle_pass_pack()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  perform private.battle_pass_record_event(new.player_id,'open_pack',1);
  return new;
end;
$$;

create or replace function private.trg_battle_pass_battle()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.status='completed' and old.status is distinct from new.status then
    perform private.battle_pass_record_event(new.challenger_id,'play_battle',1);
    perform private.battle_pass_record_event(new.opponent_id,'play_battle',1);
    if new.winner_id is not null then
      perform private.battle_pass_record_event(new.winner_id,'win_battle',1);
      if coalesce(new.is_ranked,false) then perform private.battle_pass_record_event(new.winner_id,'ranked_win',1); end if;
    end if;
  end if;
  return new;
end;
$$;

create or replace function private.trg_battle_pass_trade()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.status='completed' and old.status is distinct from new.status then
    perform private.battle_pass_record_event(new.sender_id,'complete_trade',1);
    perform private.battle_pass_record_event(new.receiver_id,'complete_trade',1);
  end if;
  return new;
end;
$$;

create or replace function private.trg_battle_pass_market_insert()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.status='active' then perform private.battle_pass_record_event(new.seller_id,'market_list',1); end if;
  return new;
end;
$$;

create or replace function private.trg_battle_pass_market_sold()
returns trigger language plpgsql security definer set search_path='' as $$
begin
  if new.status='sold' and old.status is distinct from new.status then
    perform private.battle_pass_record_event(new.seller_id,'market_sell',1);
    if new.buyer_id is not null then perform private.battle_pass_record_event(new.buyer_id,'market_buy',1); end if;
  end if;
  return new;
end;
$$;

