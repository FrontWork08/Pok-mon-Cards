create or replace function private.battle_pass_xp_to_reach_level(p_level integer)
returns bigint language sql immutable set search_path='' as $$
  select coalesce(sum((500+(g-1)*30)::bigint),0)
  from generate_series(1,greatest(0,least(coalesce(p_level,1),50)-1)) g;
$$;

create or replace function private.battle_pass_level_for_xp(p_xp bigint)
returns integer language sql immutable set search_path='' as $$
  select coalesce(max(lvl),1) from generate_series(1,50) lvl
  where greatest(coalesce(p_xp,0),0)>=private.battle_pass_xp_to_reach_level(lvl);
$$;

create or replace function private.battle_pass_period_key(p_period text,p_season_id text,p_at timestamptz default now())
returns text language sql stable set search_path='' as $$
  select case p_period
    when 'daily' then to_char(timezone('America/Sao_Paulo',p_at),'YYYY-MM-DD')
    when 'weekly' then to_char(timezone('America/Sao_Paulo',p_at),'IYYY-"W"IW')
    else p_season_id
  end;
$$;

create or replace function private.battle_pass_record_event(p_player_id uuid,p_event_key text,p_amount integer default 1)
returns void language plpgsql security definer set search_path='' as $$
declare
  v_season public.battle_pass_seasons%rowtype;
  v_mission public.battle_pass_missions%rowtype;
  v_period_key text;
  v_progress integer;
  v_xp_gain bigint:=0;
  v_cap bigint:=private.battle_pass_xp_to_reach_level(50);
begin
  if p_player_id is null or p_amount is null or p_amount<=0 then return; end if;
  select * into v_season from public.battle_pass_seasons
  where active=true and starts_at<=now() and ends_at>now()
  order by starts_at desc limit 1;
  if v_season.id is null then return; end if;

  insert into public.battle_pass_player_progress(player_id,season_id)
  values(p_player_id,v_season.id) on conflict(player_id,season_id) do nothing;

  for v_mission in
    select * from public.battle_pass_missions
    where season_id=v_season.id and active=true and event_key=p_event_key
    order by sort_order
  loop
    v_period_key:=private.battle_pass_period_key(v_mission.period,v_season.id,now());
    insert into public.battle_pass_mission_progress(player_id,mission_id,period_key,progress,updated_at)
    values(p_player_id,v_mission.id,v_period_key,least(v_mission.target,p_amount),now())
    on conflict(player_id,mission_id,period_key) do update
    set progress=least(v_mission.target,public.battle_pass_mission_progress.progress+excluded.progress),updated_at=now()
    returning progress into v_progress;

    if v_progress>=v_mission.target then
      update public.battle_pass_mission_progress
      set xp_awarded=true,completed_at=coalesce(completed_at,now()),updated_at=now()
      where player_id=p_player_id and mission_id=v_mission.id and period_key=v_period_key and xp_awarded=false;
      if found then v_xp_gain:=v_xp_gain+v_mission.xp_reward; end if;
    end if;
  end loop;

  if v_xp_gain>0 then
    update public.battle_pass_player_progress
    set xp=least(v_cap,xp+v_xp_gain),
        level=private.battle_pass_level_for_xp(least(v_cap,xp+v_xp_gain)),
        updated_at=now()
    where player_id=p_player_id and season_id=v_season.id;
  end if;
end;
$$;

create or replace function public.get_my_battle_pass()
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  v_player_id uuid:=auth.uid();
  v_season public.battle_pass_seasons%rowtype;
  v_progress public.battle_pass_player_progress%rowtype;
  v_rewards jsonb:='[]'::jsonb;
  v_missions jsonb:='[]'::jsonb;
  v_level_start bigint;
  v_next_level_cost bigint;
begin
  if v_player_id is null then raise exception 'UNAUTHENTICATED'; end if;
  select * into v_season from public.battle_pass_seasons
  where active=true and starts_at<=now() and ends_at>now()
  order by starts_at desc limit 1;
  if v_season.id is null then return null; end if;

  insert into public.battle_pass_player_progress(player_id,season_id)
  values(v_player_id,v_season.id) on conflict(player_id,season_id) do nothing;
  select * into v_progress from public.battle_pass_player_progress
  where player_id=v_player_id and season_id=v_season.id;

  v_level_start:=private.battle_pass_xp_to_reach_level(v_progress.level);
  v_next_level_cost:=case when v_progress.level>=v_season.max_level then 0
    else private.battle_pass_xp_to_reach_level(v_progress.level+1)-v_level_start end;

  select coalesce(jsonb_agg(jsonb_build_object(
    'level',r.level,'track',r.track,'label',r.label,'reward',r.reward,'claimed',(c.player_id is not null)
  ) order by r.level,case when r.track='free' then 0 else 1 end),'[]'::jsonb)
  into v_rewards
  from public.battle_pass_reward_definitions r
  left join public.battle_pass_reward_claims c
    on c.player_id=v_player_id and c.season_id=r.season_id and c.level=r.level and c.track=r.track
  where r.season_id=v_season.id and r.level between 1 and v_season.max_level;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id',m.id,'title',m.title,'description',m.description,'eventKey',m.event_key,
    'period',m.period,'periodKey',private.battle_pass_period_key(m.period,v_season.id,now()),
    'target',m.target,'xpReward',m.xp_reward,'progress',least(m.target,coalesce(mp.progress,0)),
    'completed',coalesce(mp.xp_awarded,false),'completedAt',mp.completed_at
  ) order by case m.period when 'daily' then 0 when 'weekly' then 1 else 2 end,m.sort_order),'[]'::jsonb)
  into v_missions
  from public.battle_pass_missions m
  left join public.battle_pass_mission_progress mp
    on mp.player_id=v_player_id and mp.mission_id=m.id
   and mp.period_key=private.battle_pass_period_key(m.period,v_season.id,now())
  where m.season_id=v_season.id and m.active=true;

  return jsonb_build_object(
    'season',jsonb_build_object(
      'id',v_season.id,'name',v_season.name,'startsAt',v_season.starts_at,'endsAt',v_season.ends_at,
      'maxLevel',v_season.max_level,'vipPriceDiamonds',v_season.vip_price_diamonds,
      'totalXpRequired',private.battle_pass_xp_to_reach_level(v_season.max_level)
    ),
    'progress',jsonb_build_object(
      'xp',v_progress.xp,'level',v_progress.level,'vipUnlocked',v_progress.vip_unlocked,
      'vipUnlockedAt',v_progress.vip_unlocked_at,'xpIntoLevel',greatest(0,v_progress.xp-v_level_start),
      'xpForNextLevel',v_next_level_cost
    ),
    'rewards',v_rewards,'missions',v_missions
  );
end;
$$;

create or replace function public.purchase_battle_pass_vip()
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  v_player_id uuid:=auth.uid();
  v_season public.battle_pass_seasons%rowtype;
  v_progress public.battle_pass_player_progress%rowtype;
  v_balance bigint;
begin
  if v_player_id is null then raise exception 'UNAUTHENTICATED'; end if;
  if exists(select 1 from public.app_runtime_status where id=1 and maintenance_enabled=true) then raise exception 'APP_MAINTENANCE'; end if;

  select * into v_season from public.battle_pass_seasons
  where active=true and starts_at<=now() and ends_at>now()
  order by starts_at desc limit 1;
  if v_season.id is null then raise exception 'NO_ACTIVE_BATTLE_PASS'; end if;

  insert into public.battle_pass_player_progress(player_id,season_id)
  values(v_player_id,v_season.id) on conflict(player_id,season_id) do nothing;
  select * into v_progress from public.battle_pass_player_progress
  where player_id=v_player_id and season_id=v_season.id for update;

  if v_progress.vip_unlocked then
    select diamonds into v_balance from public.players where id=v_player_id;
    return jsonb_build_object('vipUnlocked',true,'diamonds',v_balance,'alreadyUnlocked',true);
  end if;

  update public.players set diamonds=diamonds-v_season.vip_price_diamonds
  where id=v_player_id and diamonds>=v_season.vip_price_diamonds
  returning diamonds into v_balance;
  if not found then raise exception 'NOT_ENOUGH_DIAMONDS'; end if;

  update public.battle_pass_player_progress
  set vip_unlocked=true,vip_unlocked_at=now(),updated_at=now()
  where player_id=v_player_id and season_id=v_season.id;

  return jsonb_build_object('vipUnlocked',true,'diamonds',v_balance,'priceDiamonds',v_season.vip_price_diamonds,'alreadyUnlocked',false);
end;
$$;

create or replace function public.claim_battle_pass_reward(p_level integer,p_track text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  v_player_id uuid:=auth.uid();
  v_season public.battle_pass_seasons%rowtype;
  v_progress public.battle_pass_player_progress%rowtype;
  v_reward jsonb;
  v_coins bigint:=0;
  v_diamonds bigint:=0;
  v_new_coins bigint;
  v_new_diamonds bigint;
begin
  if v_player_id is null then raise exception 'UNAUTHENTICATED'; end if;
  if p_track not in ('free','vip') then raise exception 'INVALID_TRACK'; end if;
  if exists(select 1 from public.app_runtime_status where id=1 and maintenance_enabled=true) then raise exception 'APP_MAINTENANCE'; end if;

  select * into v_season from public.battle_pass_seasons
  where active=true and starts_at<=now() and ends_at>now()
  order by starts_at desc limit 1;
  if v_season.id is null then raise exception 'NO_ACTIVE_BATTLE_PASS'; end if;
  if p_level<1 or p_level>v_season.max_level then raise exception 'INVALID_LEVEL'; end if;

  insert into public.battle_pass_player_progress(player_id,season_id)
  values(v_player_id,v_season.id) on conflict(player_id,season_id) do nothing;
  select * into v_progress from public.battle_pass_player_progress
  where player_id=v_player_id and season_id=v_season.id for update;

  if p_level>v_progress.level then raise exception 'LEVEL_LOCKED'; end if;
  if p_track='vip' and not v_progress.vip_unlocked then raise exception 'VIP_REQUIRED'; end if;

  select reward into v_reward from public.battle_pass_reward_definitions
  where season_id=v_season.id and level=p_level and track=p_track;
  if v_reward is null then raise exception 'REWARD_NOT_FOUND'; end if;

  insert into public.battle_pass_reward_claims(player_id,season_id,level,track,reward)
  values(v_player_id,v_season.id,p_level,p_track,v_reward)
  on conflict(player_id,season_id,level,track) do nothing;
  if not found then raise exception 'REWARD_ALREADY_CLAIMED'; end if;

  v_coins:=coalesce((v_reward->>'coins')::bigint,0);
  v_diamonds:=coalesce((v_reward->>'diamonds')::bigint,0);
  update public.players set coins=coins+v_coins,diamonds=diamonds+v_diamonds
  where id=v_player_id returning coins,diamonds into v_new_coins,v_new_diamonds;
  if not found then raise exception 'PLAYER_NOT_FOUND'; end if;

  return jsonb_build_object('level',p_level,'track',p_track,'reward',v_reward,'coins',v_new_coins,'diamonds',v_new_diamonds);
end;
$$;

create or replace function public.server_admin_grant_battle_pass_vip(p_actor_id uuid,p_target_ids uuid[],p_note text default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  v_season public.battle_pass_seasons%rowtype;
  v_count integer:=0;
  v_recipients jsonb:='[]'::jsonb;
begin
  if p_actor_id is null or not exists(select 1 from public.admin_members where player_id=p_actor_id) then raise exception 'FORBIDDEN'; end if;
  if p_target_ids is null or coalesce(array_length(p_target_ids,1),0)<1 or array_length(p_target_ids,1)>100 then raise exception 'INVALID_TARGETS'; end if;

  select * into v_season from public.battle_pass_seasons
  where active=true and starts_at<=now() and ends_at>now()
  order by starts_at desc limit 1;
  if v_season.id is null then raise exception 'NO_ACTIVE_BATTLE_PASS'; end if;

  with targets as (select distinct x as player_id from unnest(p_target_ids) x),
  valid as (select p.id,p.username from public.players p join targets t on t.player_id=p.id),
  granted as (
    insert into public.battle_pass_player_progress(player_id,season_id,vip_unlocked,vip_unlocked_at,updated_at)
    select id,v_season.id,true,now(),now() from valid
    on conflict(player_id,season_id) do update
      set vip_unlocked=true,
          vip_unlocked_at=coalesce(public.battle_pass_player_progress.vip_unlocked_at,excluded.vip_unlocked_at),
          updated_at=now()
    returning player_id
  )
  select count(*) into v_count from granted;

  insert into public.battle_pass_admin_grants(actor_id,target_id,season_id,note)
  select p_actor_id,p.id,v_season.id,nullif(trim(coalesce(p_note,'')),'')
  from public.players p where p.id in (select distinct x from unnest(p_target_ids) x);

  select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'username',p.username) order by p.username),'[]'::jsonb)
  into v_recipients from public.players p
  where p.id in (select distinct x from unnest(p_target_ids) x);

  return jsonb_build_object('seasonId',v_season.id,'recipientCount',v_count,'recipients',v_recipients);
end;
$$;

