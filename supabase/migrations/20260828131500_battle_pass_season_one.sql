-- Battle Pass Season 1: server-owned progression, missions, rewards and VIP.
-- Battle Pass XP is intentionally separate from the account level XP.

create table if not exists public.battle_pass_seasons (
  id text primary key,
  name text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  max_level integer not null default 50 check (max_level between 1 and 100),
  vip_price_diamonds integer not null default 25 check (vip_price_diamonds >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);
create index if not exists battle_pass_seasons_active_window_idx on public.battle_pass_seasons(active,starts_at,ends_at);

create table if not exists public.battle_pass_reward_definitions (
  season_id text not null references public.battle_pass_seasons(id) on delete cascade,
  level integer not null check (level between 1 and 100),
  track text not null check (track in ('free','vip')),
  label text not null,
  reward jsonb not null default '{}'::jsonb,
  primary key (season_id,level,track)
);
create index if not exists battle_pass_rewards_season_level_idx on public.battle_pass_reward_definitions(season_id,level);

create table if not exists public.battle_pass_missions (
  id text primary key,
  season_id text not null references public.battle_pass_seasons(id) on delete cascade,
  title text not null,
  description text not null default '',
  event_key text not null,
  period text not null check (period in ('daily','weekly','season')),
  target integer not null check (target > 0),
  xp_reward integer not null check (xp_reward > 0),
  sort_order integer not null default 0,
  active boolean not null default true
);
create index if not exists battle_pass_missions_event_idx on public.battle_pass_missions(season_id,event_key,active);
create index if not exists battle_pass_missions_display_idx on public.battle_pass_missions(season_id,period,sort_order);

create table if not exists public.battle_pass_player_progress (
  player_id uuid not null references public.players(id) on delete cascade,
  season_id text not null references public.battle_pass_seasons(id) on delete cascade,
  xp bigint not null default 0 check (xp >= 0),
  level integer not null default 1 check (level between 1 and 100),
  vip_unlocked boolean not null default false,
  vip_unlocked_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (player_id,season_id)
);
create index if not exists battle_pass_player_progress_season_level_idx on public.battle_pass_player_progress(season_id,level desc);

create table if not exists public.battle_pass_mission_progress (
  player_id uuid not null references public.players(id) on delete cascade,
  mission_id text not null references public.battle_pass_missions(id) on delete cascade,
  period_key text not null,
  progress integer not null default 0 check (progress >= 0),
  xp_awarded boolean not null default false,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (player_id,mission_id,period_key)
);
create index if not exists battle_pass_mission_progress_player_idx on public.battle_pass_mission_progress(player_id,updated_at desc);
create index if not exists battle_pass_mission_progress_mission_idx on public.battle_pass_mission_progress(mission_id,updated_at desc);

create table if not exists public.battle_pass_reward_claims (
  player_id uuid not null references public.players(id) on delete cascade,
  season_id text not null references public.battle_pass_seasons(id) on delete cascade,
  level integer not null,
  track text not null check (track in ('free','vip')),
  reward jsonb not null,
  claimed_at timestamptz not null default now(),
  primary key (player_id,season_id,level,track)
);
create index if not exists battle_pass_reward_claims_player_idx on public.battle_pass_reward_claims(player_id,season_id,claimed_at desc);
create index if not exists battle_pass_reward_claims_season_idx on public.battle_pass_reward_claims(season_id,claimed_at desc);

create table if not exists public.battle_pass_admin_grants (
  id bigint generated by default as identity primary key,
  actor_id uuid not null references public.players(id) on delete restrict,
  target_id uuid not null references public.players(id) on delete cascade,
  season_id text not null references public.battle_pass_seasons(id) on delete cascade,
  note text,
  created_at timestamptz not null default now()
);
create index if not exists battle_pass_admin_grants_target_idx on public.battle_pass_admin_grants(target_id,created_at desc);
create index if not exists battle_pass_admin_grants_actor_idx on public.battle_pass_admin_grants(actor_id,created_at desc);
create index if not exists battle_pass_admin_grants_season_idx on public.battle_pass_admin_grants(season_id,created_at desc);

